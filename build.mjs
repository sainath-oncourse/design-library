// Builds site/data.js from data/*.json so the site opens straight from disk (no server).
// Run: node build.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const read = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : []);
const sources = read("data/sources.json");
const experiments = read("data/experiments.json");
const lessons = read("data/lessons.json");

const slug = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "").slice(0, 70);

const seen = new Set();
for (const s of sources) {
  if (!s.Title || !s.Link) throw new Error(`Source missing Title or Link: ${JSON.stringify(s).slice(0, 120)}`);
  if (seen.has(s.Link)) throw new Error(`Duplicate link: ${s.Link}`);
  seen.add(s.Link);
  s.id = slug(s.Title);
}

const byTitle = Object.fromEntries(sources.map((s) => [s.Title, s.id]));
for (const l of lessons) for (const i of l.ideas) {
  i.sourceIds = i.sources.map((t) => { if (!byTitle[t]) throw new Error(`Lesson "${l.title}" cites a source that isn't in the library: ${t}`); return byTitle[t]; });
}

writeFileSync(
  "site/data.js",
  `// Generated by build.mjs from data/*.json. Don't edit by hand.\nwindow.LIBRARY = ${JSON.stringify({ sources, experiments, lessons, built: new Date().toISOString().slice(0, 10) }, null, 1)};\n`
);
console.log(`Built site/data.js: ${sources.length} sources, ${lessons.length} lessons, ${experiments.length} experiments`);

// Also write one self-contained file that opens anywhere (double-click, any browser, attachments).
const html = readFileSync("site/index.html", "utf8")
  .replace('<link rel="stylesheet" href="styles.css" />', () => `<style>${readFileSync("site/styles.css", "utf8")}</style>`)
  .replace('<script src="data.js"></script>', () => `<script>${readFileSync("site/data.js", "utf8")}</script>`)
  .replace('<script src="app.js"></script>', () => `<script>${readFileSync("site/app.js", "utf8")}</script>`);
writeFileSync("design-library.html", html);
writeFileSync("index.html", html);
console.log("Built design-library.html");
